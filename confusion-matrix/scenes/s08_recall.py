def magnifier(color=ORANGE_, s=0.5):
    lens = Circle(0.35 * s * 2).set_stroke(color, 5)
    handle = Line(ORIGIN, DR * 0.45 * s * 2).set_stroke(color, 7).next_to(lens, DR, buff=-0.08)
    g = VGroup(lens, handle)
    for x in g: x.qa_ignore = True
    return g



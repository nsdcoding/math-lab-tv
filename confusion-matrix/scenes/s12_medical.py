import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from cm import *

MED = dict(TP=9, FN=1, FP=99, TN=891)
CLINIC = dict(TP=450, FN=50, FP=50, TN=450)
ROWS = ("really sick", "healthy")
COLS = ("positive", "negative")


class S12Medical(Base):
    CHAPTER = "Example: A Medical Test"

    def construct(self):
        # ── s145 more examples ──
        self.at("s145", 0.0)
        ex = VGroup(*[pill(t, c, 30) for t, c in (("medical test", RED_), ("spam filter", BLUE_), ("loans", WARN))]).arrange(RIGHT, buff=0.5)
        ex.move_to(UP * 0.4)
        self.play(LaggedStart(*[FadeIn(e, shift=UP * 0.15) for e in ex], lag_ratio=0.15), run_time=0.8)
        self.word("s145", "real")
        self.play(highlight(ex[0], color=RED_), run_time=0.8)
        # ── s146 the Bayes test ──
        self.at("s146", 0.0)
        self.play(FadeOut(ex), run_time=0.4)
        cue = card_cue("Bayes' Theorem", mini_bayes(), VIOLET)
        self.word("s146", "screening")
        self.play(FadeIn(cue, shift=LEFT * 0.2), run_time=0.5)
        # ── s147 1,000 people: 10 sick, 990 healthy ──
        self.at("s147", 0.0)
        g = grid_at(rows=ROWS, cols=COLS, col_title="the test said")
        self.play(FadeIn(VGroup(g.cells, g.names, g.collab, g.coltitle, g.rowlab, g.rowtitle)), run_time=0.7)
        t0 = pill("10", ORANGE_, 26).next_to(g.row0(), RIGHT, buff=0.22)
        t1 = pill("990", INK2, 26).next_to(g.row1(), RIGHT, buff=0.22)
        tl = T("1,000 people · 1 in 100 sick", 24, INK2, weight=BOLD).move_to(RIGHT * (PANEL_X + 0.15) + UP * 1.2)
        self.play(FadeIn(tl), run_time=0.4)
        self.word("s147", "ten")
        self.play(FadeIn(t0), run_time=0.4)
        self.word("s147", "nine")
        self.play(FadeIn(t1), run_time=0.4)
        # ── s148 / s149 fill ──
        self.at("s148", 0.0)
        self.word("s148", "nine", nth=1)
        self.play(g.set_num("TP", 9), g.light("TP"), run_time=0.5)
        self.word("s148", "one")
        self.play(g.set_num("FN", 1), g.light("FN"), run_time=0.5)
        self.at("s149", 0.0)
        self.word("s149", "ninety-nine")
        self.play(g.set_num("FP", 99), g.light("FP"), run_time=0.5)
        self.word("s149", "eight")
        self.play(g.set_num("TN", 891), g.light("TN"), run_time=0.5)
        # ── s150 recall 90% ──
        self.at("s150", 0.0)
        self.play(FadeOut(tl), run_time=0.3)
        fr = g.frame_of(g.row0(), ORANGE_)
        rl = T("recall  9/10 = 90%", 24, ORANGE_, weight=BOLD).move_to(RIGHT * (PANEL_X + 0.15) + UP * 1.3)
        self.play(Create(fr), FadeIn(rl), run_time=0.6)
        # ── s151 accuracy 90% ──
        self.at("s151", 0.0)
        self.play(FadeOut(fr), run_time=0.3)
        al = T("accuracy  900/1,000 = 90%", 24, WARN, weight=BOLD).next_to(rl, DOWN, buff=0.3)
        self.word("s151", "Accuracy:")
        self.play(highlight(g.cell["TP"], g.cell["TN"], color=WARN), FadeIn(al), run_time=0.8)
        # ── s152 / s153 precision = 1 in 12 ──
        self.at("s152", 0.0)
        fc = g.frame_of(g.col0(), VIOLET)
        self.word("s152", "alarm")
        self.play(Create(fc), run_time=0.6)
        pl = T("precision  9/108", 24, VIOLET, weight=BOLD).next_to(al, DOWN, buff=0.3)
        self.word("s152", "Nine", nth=1)
        self.play(FadeIn(pl), run_time=0.5)
        self.at("s153", 0.0)
        one = TB("= 1 in 12", 44, VIOLET).next_to(pl, DOWN, buff=0.3)
        same = pill("same as Bayes", VIOLET, 24).next_to(one, DOWN, buff=0.25)
        self.play(FadeIn(one), run_time=0.5)
        self.word("s153", "same")
        self.play(FadeIn(same), run_time=0.4)
        # ── s154 Bayes was a precision calculation ──
        self.at("s154", 0.0)
        self.play(FadeOut(VGroup(rl, al, pl, one, same)), run_time=0.4)
        bc = side_card([T("chance of sick,", 24, INK), T("given a positive test", 24, INK), T("= precision", 30, VIOLET, weight=BOLD)], VIOLET, 26,
                       title="Bayes' theorem", title_color=VIOLET).move_to(RIGHT * (PANEL_X + 0.15) + UP * 0.2)
        self.word("s154", "secretly")
        self.play(FadeIn(bc, shift=LEFT * 0.2), run_time=0.6)

        # ── s155 – s159 same test, different crowd ──
        self.at("s155", 0.0)
        self.play(FadeOut(VGroup(bc, fc, cue, t0, t1)), run_time=0.4)
        small = grid_at(0.55, np.array([-3.35, -0.45, 0]), counts=MED, names=False, rows=("sick", "healthy"),
                        cols=COLS, row_title="", col_title="", label_size=40, num_size=70, show_lit=True)
        self.play(ReplacementTransform(VGroup(g.cells, *[g.num[k] for k in KEYS], g.collab, g.rowlab),
                                       VGroup(small.cells, *[small.num[k] for k in KEYS], small.collab, small.rowlab)),
                  FadeOut(VGroup(g.names, g.coltitle, g.rowtitle)), run_time=0.9)
        h1 = pill("screening: 1 in 100 sick", RED_, 24).move_to(np.array([-3.35, 1.85, 0]))
        cl = grid_at(0.55, np.array([3.6, -0.45, 0]), names=False, rows=("sick", "healthy"), cols=COLS,
                     row_title="", col_title="", label_size=40, num_size=70)
        h2 = pill("clinic: 1 in 2 sick", AQUA, 24).move_to(np.array([3.6, 1.85, 0]))
        self.word("s155", "different")
        self.play(FadeIn(h1), FadeIn(h2), FadeIn(VGroup(cl.cells, cl.collab, cl.rowlab)), run_time=0.6)
        self.at("s156", 0.0)
        self.word("s156", "Five")
        tt = T("500 sick · 500 healthy", 24, INK2).move_to(np.array([3.6, 1.3, 0]))
        self.play(FadeIn(tt), run_time=0.4)
        self.at("s157", 0.0)
        self.word("s157", "Four")
        self.play(cl.set_num("TP", 450), cl.light("TP"), run_time=0.5)
        self.word("s157", "fifty", nth=1)
        self.play(cl.set_num("FN", 50), cl.light("FN"), run_time=0.5)
        self.at("s158", 0.0)
        self.word("s158", "Fifty")
        self.play(cl.set_num("FP", 50), cl.light("FP"), run_time=0.5)
        self.word("s158", "four")
        self.play(cl.set_num("TN", 450), cl.light("TN"), run_time=0.5)
        self.at("s159", 0.0)
        self.play(FadeOut(tt), run_time=0.3)
        r1 = T("recall 90%", 26, ORANGE_, weight=BOLD).move_to(np.array([-3.35, -2.05, 0]))
        r2 = T("recall 90%", 26, ORANGE_, weight=BOLD).move_to(np.array([3.6, -2.05, 0]))
        self.word("s159", "Recall")
        self.play(FadeIn(r1), FadeIn(r2), run_time=0.5)
        p1 = T("precision 1 in 12", 26, VIOLET, weight=BOLD).move_to(np.array([-3.35, -2.05, 0]))
        p2 = T("precision 450/500 = 90%", 26, VIOLET, weight=BOLD).move_to(np.array([3.6, -2.05, 0]))
        self.word("s159", "precision")
        self.play(FadeOut(r1), FadeOut(r2), FadeIn(p1), FadeIn(p2), run_time=0.6)
        # ── s160 precision depends on how common it is ──
        self.at("s160", 0.0)
        rr = T("recall: unchanged", 26, ORANGE_, weight=BOLD).move_to(UP * 2.6 + RIGHT * 0.3)
        self.word("s160", "Recall")
        self.play(FadeIn(rr), run_time=0.4)
        self.word("s160", "Precision")
        self.play(highlight(p1, p2, color=VIOLET), run_time=0.8)
        dep = pill("precision depends on how common it is", VIOLET, 26).move_to(DOWN * 2.05 + RIGHT * 0.1)
        self.word("s160", "depends")
        self.play(FadeOut(VGroup(p1, p2)), FadeIn(dep), run_time=0.5)
        # ── s161 / s162 medicine: recall first, then confirm ──
        self.at("s161", 0.0)
        self.play(FadeOut(VGroup(rr, dep, h2, grid_mobs(cl))), run_time=0.5)
        self.play(VGroup(grid_mobs(small), h1).animate.shift(RIGHT * 0.9), run_time=0.6)
        cost = pill("a miss is the costly mistake", BLUE_, 26).move_to(RIGHT * 3.6 + UP * 0.9)
        self.word("s161", "Missing")
        self.play(highlight(small.cell["FN"], color=BLUE_), FadeIn(cost), run_time=0.8)
        self.at("s162", 0.0)
        st = side_card(["every positive gets", "a second, careful test"], AQUA, 24, title="then confirm", title_color=AQUA)
        st.move_to(RIGHT * 3.6 + DOWN * 0.8)
        self.word("s162", "second,")
        self.play(FadeIn(st, shift=LEFT * 0.2), run_time=0.6)
        self.until(SEGS["s162"]["end"] + 0.1)
        self.play(FadeOut(VGroup(grid_mobs(small), h1, cost, st)), run_time=0.5)
        self.finish()

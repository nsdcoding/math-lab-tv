import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from pkit import *

RX = 3.7


class S14Or(PBase):
    CHAPTER = "The Word OR"

    def construct(self):
        self.at("s214")
        w = VGroup(*[pill(x, c, 44) for x, c in (("NOT", BLUE_), ("OR", AQUA), ("AND", ORANGE_))]).arrange(RIGHT, buff=0.8).move_to(UP * 0.4)
        self.play(FadeIn(w), run_time=0.5)
        self.play(w[0].animate.set_opacity(0.25), w[2].animate.set_opacity(0.25), w[1].animate.scale(1.3), run_time=0.6)
        self.play(FadeOut(w[0]), FadeOut(w[2]), w[1].animate.scale(0.75).move_to(UP * 2.85), run_time=0.6)
        # s215–s219 seven or eleven
        self.at("s215")
        g = DiceGrid(0.62, fs=26).move_to(LEFT * 3.0 + DOWN * 0.05)
        sums = g.sums()
        q = T("7 or 11?", 44, INK, weight=BOLD).move_to(RIGHT * RX + UP * 2.0)
        self.play(FadeIn(g), FadeIn(sums), run_time=0.6)
        self.w("s215", "seven")
        self.play(FadeIn(q), run_time=0.4)
        self.at("s216")
        self.play(*g.tint(lambda a, b: a + b == 7, AQUA, 0.9), run_time=0.5)
        l7 = T("7: 6 squares", 32, AQUA, weight=BOLD).move_to(RIGHT * RX + UP * 1.15)
        self.play(FadeIn(l7), run_time=0.3)
        self.w("s216", "eleven")
        self.play(*g.tint(lambda a, b: a + b == 11, VIOLET, 0.9), run_time=0.5)
        l11 = T("11: 2 squares", 32, VIOLET, weight=BOLD).next_to(l7, DOWN, buff=0.3)
        self.play(FadeIn(l11), run_time=0.3)
        self.at("s217")
        ns = pill("no shared squares", WARN, 30).next_to(l11, DOWN, buff=0.45)
        self.play(FadeIn(ns), run_time=0.5)
        self.at("s218")
        e = MathTex(r"{6 \over 36} + {2 \over 36} = {8 \over 36}", font_size=54, color=VIOLET).next_to(ns, DOWN, buff=0.4)
        self.play(Write(e), run_time=1.2)
        self.at("s219")
        self.play(FadeOut(VGroup(l7, l11, ns, e, q)), run_time=0.4)
        r1 = MathTex(r"P(A \text{ or } B) = P(A) + P(B)", font_size=46, color=INK)
        rc = VGroup(T("can't happen together:", 30, WARN, weight=BOLD), r1).arrange(DOWN, buff=0.3)
        rcb = boxed(rc, WARN, pad=0.35).move_to(RIGHT * RX + UP * 0.4)
        if rcb.width > 6.6: rcb.scale_to_fit_width(6.6)
        self.play(FadeIn(rcb), run_time=0.8)
        # s220–s227 orange 6 or blue 6
        self.at("s220")
        caut = TB("careful!", 48, RED_).move_to(RIGHT * RX + DOWN * 1.4)
        self.play(FadeIn(caut, scale=1.4), *g.reset(), run_time=0.5)
        self.at("s221")
        self.play(FadeOut(VGroup(rcb, caut)), run_time=0.3)
        q = T("orange 6 OR blue 6?", 40, INK, weight=BOLD).move_to(RIGHT * RX + UP * 1.6)
        self.play(FadeIn(q), run_time=0.4)
        self.at("s222")
        self.play(*g.tint(lambda a, b: a == 6, ORANGE_, 0.75), run_time=0.5)
        lo = T("orange 6: 6 squares", 30, ORANGE_, weight=BOLD).move_to(RIGHT * RX + UP * 0.7)
        self.play(FadeIn(lo), run_time=0.3)
        self.at("s223")
        self.play(*g.tint(lambda a, b: b == 6 and a != 6, BLUE_, 0.75), run_time=0.5)
        lb = T("blue 6: 6 squares", 30, BLUE_, weight=BOLD).next_to(lo, DOWN, buff=0.3)
        self.play(FadeIn(lb), run_time=0.3)
        self.at("s224")
        w12 = MathTex(r"6 + 6 = 12\;?", font_size=54, color=MUTED).next_to(lb, DOWN, buff=0.45)
        self.play(Write(w12), run_time=0.7)
        self.at("s225")
        self.w("s225", "cross")
        self.play(g.c(6, 6).animate.set_fill(WARN, 0.95), run_time=0.4)
        x2 = pill("counted twice", WARN, 26).next_to(g, UP, buff=0.12).align_to(g.c(6, 6), RIGHT)
        self.w("s225", "twice")
        self.play(FadeIn(x2, shift=LEFT * 0.2), run_time=0.4)
        self.at("s226")
        xx = cross(RED_, 0.45).move_to(w12); [setattr(m, "qa_ignore", True) for m in xx]
        e11 = MathTex(r"6 + 6 - 1 = 11", font_size=54, color=INK).next_to(w12, DOWN, buff=0.35)
        self.play(Create(xx), run_time=0.4)
        self.play(Write(e11), run_time=0.8)
        self.at("s227")
        a11 = MathTex(r"{11 \over 36}", font_size=72, color=VIOLET).move_to(e11)
        self.play(FadeOut(VGroup(w12, xx)), ReplacementTransform(e11, a11), run_time=0.6)
        self.play(*g.tint(lambda a, b: a == 6 or b == 6, VIOLET, 0.8), run_time=0.5)
        # s228 full rule
        self.at("s228")
        self.play(FadeOut(VGroup(g, sums, q, lo, lb, a11, x2)), run_time=0.4)
        fr_ = MathTex(r"P(A \text{ or } B)", "=", r"P(A)", "+", r"P(B)", "-", r"P(A \text{ and } B)", font_size=64)
        fr_[2].set_color(ORANGE_); fr_[4].set_color(BLUE_); fr_[6].set_color(WARN); fr_[0].set_color(VIOLET)
        frb = boxed(fr_, VIOLET, pad=0.4).move_to(UP * 0.6)
        ov = T("the overlap, so it isn't counted twice", 30, WARN).next_to(frb, DOWN, buff=0.35).align_to(frb, RIGHT)
        self.play(FadeIn(frb[0]), Write(fr_), run_time=1.6)
        self.w("s228", "overlap")
        self.play(FadeIn(ov), Indicate(fr_[6], color=WARN), run_time=0.8)
        # s229 circles
        self.at("s229")
        self.play(FadeOut(ov), FadeOut(w[1]), frb.animate.scale(0.6).move_to(UP * 2.5), run_time=0.5)
        ca = Circle(1.5, stroke_color=ORANGE_, stroke_width=5, fill_color=ORANGE_, fill_opacity=0.25).move_to(LEFT * 2.7 + DOWN * 0.6)
        cb = Circle(1.5, stroke_color=BLUE_, stroke_width=5, fill_color=BLUE_, fill_opacity=0.25).move_to(LEFT * 0.9 + DOWN * 0.6)
        la = T("A", 44, ORANGE_, weight=BOLD).move_to(ca.get_center() + LEFT * 0.7)
        lbb = T("B", 44, BLUE_, weight=BOLD).move_to(cb.get_center() + RIGHT * 0.7)
        self.play(DrawBorderThenFill(ca), DrawBorderThenFill(cb), FadeIn(la), FadeIn(lbb), run_time=1.0)
        lens = Intersection(ca, cb, fill_color=WARN, fill_opacity=0.75, stroke_width=0)
        self.w("s229", "middle")
        self.play(FadeIn(lens), run_time=0.5)
        tw = pill("counted twice → remove once", WARN, 28).move_to(RIGHT * 3.9 + DOWN * 0.6)
        self.play(FadeIn(tw), run_time=0.5)
        # s230 no overlap
        self.at("s230")
        self.play(FadeOut(lens), FadeOut(tw), ca.animate.shift(LEFT * 0.9), la.animate.shift(LEFT * 0.9), cb.animate.shift(RIGHT * 0.9), lbb.animate.shift(RIGHT * 0.9), run_time=0.8)
        z = T("overlap = 0 → just add", 32, AQUA, weight=BOLD).move_to(DOWN * 2.3)
        z.move_to(RIGHT * 4.2 + DOWN * 0.6)
        self.play(FadeIn(z), run_time=0.5)
        # s231–s233 class of 30
        self.at("s231")
        self.clear()
        hd = header("a class of 30 (illustration)", INK, 30)
        dots_ = VGroup()
        foot = set(range(12)); mus = set(range(7, 15))   # 12 football, 8 music, 5 both (7..11)
        for k in range(30):
            d = Circle(0.26, stroke_color=INK2, stroke_width=3, fill_color=PANEL, fill_opacity=1)
            d.move_to(LEFT * 4.6 + RIGHT * (k % 10) * 0.72 + UP * (0.9 - (k // 10) * 0.72))
            dots_.add(d)
        self.play(FadeIn(hd), FadeIn(dots_, lag_ratio=0.02), run_time=0.8)
        self.w("s231", "twelve")
        self.play(*[dots_[k].animate.set_stroke(ORANGE_, 5) for k in foot], run_time=0.5)
        self.w("s231", "eight")
        self.play(*[dots_[k].animate.set_fill(BLUE_, 0.75) for k in mus], run_time=0.5)
        lg = VGroup(T("football: 12 (orange ring)", 26, ORANGE_), T("music: 8 (blue fill)", 26, BLUE_), T("both: 5", 26, WARN)).arrange(DOWN, buff=0.18, aligned_edge=LEFT)
        lg.move_to(RIGHT * 4.6 + UP * 0.2)
        self.w("s231", "five")
        self.play(FadeIn(lg), *[Indicate(dots_[k], color=WARN) for k in foot & mus], run_time=0.8)
        self.at("s232")
        e = MathTex(r"12 + 8 - 5 = 15", font_size=60, color=INK).move_to(DOWN * 1.6 + LEFT * 1.5)
        self.play(Write(e), run_time=1.2)
        self.w("s232", "fifteen")
        self.play(*[dots_[k].animate.set_fill(VIOLET, 0.85) for k in foot | mus], run_time=0.6)
        self.at("s233")
        a = MathTex(r"{15 \over 30} = {1 \over 2}", font_size=64, color=VIOLET).next_to(e, RIGHT, buff=1.0)
        self.w("s233", "fifteen")
        self.play(Write(a), run_time=0.9)
        # s234 checklist
        self.at("s234")
        self.clear()
        ck = rule_card(["OR → can both happen at once?", "yes → subtract the overlap"], AQUA, 38)
        ck.move_to(UP * 0.3)
        self.play(FadeIn(ck, scale=0.9), run_time=0.7)
        self.finish()

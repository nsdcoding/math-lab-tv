import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from pkit import *

class S18Cards(PBase):
    CHAPTER = "A Deck of Cards"

    def construct(self):
        self.at("s284")
        hd = header("NOT · OR · AND on a deck of cards", INK, 32)
        fan = VGroup(*[ic_card(INK2, 1.0, 1.4) for _ in range(7)])
        for k, c in enumerate(fan):
            c.rotate((k - 3) * 0.14, about_point=DOWN * 2.6).shift(RIGHT * (k - 3) * 0.38)
        fan.move_to(UP * 0.2)
        self.play(FadeIn(hd), LaggedStart(*[FadeIn(c) for c in fan], lag_ratio=0.1), run_time=1.0)
        # s285 grid
        self.at("s285")
        self.play(FadeOut(fan), run_time=0.3)
        g = deck_grid().move_to(UP * 0.35)
        self.play(FadeIn(g[0]), FadeIn(g[1], lag_ratio=0.01), run_time=1.0)
        self.w("s285", "suits")
        self.play(FadeIn(g[3], lag_ratio=0.2), run_time=0.8)
        self.w("s285", "thirteen")
        self.play(FadeIn(g[2], lag_ratio=0.05), run_time=0.9)
        e = TB("4 × 13 = 52", 44, WARN).move_to(DOWN * 1.9)
        self.play(Write(e), run_time=0.7)
        # s286 equally likely
        self.at("s286")
        self.play(g[1].animate.set_fill(WARN, 0.5), run_time=0.4)
        self.play(g[1].animate.set_fill(CELL_FILL, 1), run_time=0.4)
        el = pill("each card equally likely to be on top", WARN, 30).move_to(DOWN * 1.9)
        self.play(ReplacementTransform(e, el), run_time=0.5)
        # s287 heart
        self.at("s287")
        self.play(FadeOut(el), g.where(lambda r, s: s == 0).animate.set_fill(AQUA, 0.85), run_time=0.6)
        a1 = MathTex(r"P(\heartsuit) = {13 \over 52} = {1 \over 4}", font_size=54, color=VIOLET).move_to(DOWN * 1.8)
        self.w("s287", "thirteen")
        self.play(Write(a1), run_time=1.0)
        # s288 king
        self.at("s288")
        self.play(FadeOut(a1), g.where(lambda r, s: True).animate.set_fill(CELL_FILL, 1), run_time=0.4)
        self.play(g.where(lambda r, s: r == 12).animate.set_fill(AQUA, 0.85), run_time=0.5)
        a2 = MathTex(r"P(K) = {4 \over 52} = {1 \over 13}", font_size=54, color=VIOLET).move_to(DOWN * 1.8)
        self.w("s288", "four")
        self.play(Write(a2), run_time=1.0)
        # s289–s291 king or heart
        self.at("s289")
        self.play(FadeOut(a2), g.where(lambda r, s: True).animate.set_fill(CELL_FILL, 1), run_time=0.3)
        q = T("king OR heart?", 36, INK, weight=BOLD).move_to(DOWN * 1.8)
        self.play(FadeIn(q), run_time=0.4)
        self.at("s290")
        self.play(g.where(lambda r, s: s == 0).animate.set_fill(ORANGE_, 0.7), run_time=0.4)
        self.w("s290", "four")
        self.play(g.where(lambda r, s: r == 12 and s != 0).animate.set_fill(BLUE_, 0.7), run_time=0.4)
        self.w("s290", "both")
        self.play(g.cells[(12, 0)].animate.set_fill(WARN, 0.95), run_time=0.4)
        tw = pill("K♥ counted twice", WARN, 26).next_to(g, RIGHT, buff=0.15).set_y(g.cells[(12, 0)].get_y())
        tw.move_to(RIGHT * 4.6 + UP * 2.2)
        self.play(FadeIn(tw), run_time=0.4)
        self.at("s291")
        e = MathTex(r"13 + 4 - 1 = 16 \;\rightarrow\; {16 \over 52} = {4 \over 13}", font_size=50, color=VIOLET).move_to(DOWN * 1.8)
        self.play(FadeOut(q), Write(e), run_time=1.6)
        # s292 not a heart
        self.at("s292")
        self.play(FadeOut(VGroup(e, tw)), g.where(lambda r, s: True).animate.set_fill(CELL_FILL, 1), run_time=0.3)
        self.play(g.where(lambda r, s: s != 0).animate.set_fill(BLUE_, 0.5), run_time=0.4)
        e = MathTex(r"P(\text{not } \heartsuit) = 1 - {1 \over 4} = {3 \over 4}", font_size=50, color=VIOLET).move_to(DOWN * 1.8)
        self.play(Write(e), run_time=1.0)
        # s293–s297 two aces
        self.at("s293")
        self.clear()
        hd = header("two cards, no putting back: both aces?", INK, 32)
        c1 = ic_card(INK2, 1.4, 1.8); c2 = ic_card(INK2, 1.4, 1.8)
        VGroup(c1, c2).arrange(RIGHT, buff=2.6).move_to(UP * 0.85)
        self.play(FadeIn(hd), FadeIn(c1), FadeIn(c2), run_time=0.7)
        self.at("s294")
        a1 = T("A", 72, RED_, weight=BOLD).move_to(c1)
        f1 = MathTex(r"{4 \over 52}", font_size=60, color=AQUA).next_to(c1, DOWN, buff=0.3)
        self.play(FadeIn(a1), Write(f1), run_time=0.7)
        self.at("s295")
        a2 = T("A", 72, INK2, weight=BOLD).move_to(c2)
        f2 = MathTex(r"{3 \over 51}", font_size=60, color=AQUA).next_to(c2, DOWN, buff=0.3)
        lf = T("3 aces left, 51 cards", 26, WARN).next_to(c2, RIGHT, buff=0.4)
        self.play(FadeIn(a2), Write(f2), FadeIn(lf), run_time=0.8)
        self.at("s296")
        tm = MathTex(r"\times", font_size=60, color=INK2).move_to((f1.get_center() + f2.get_center()) / 2)
        res = MathTex(r"= {1 \over 221}", font_size=56, color=VIOLET).move_to(DOWN * 2.0)
        self.play(FadeIn(tm), run_time=0.4)
        self.w("s296", "one", nth=0)
        self.play(Write(res), run_time=0.9)
        self.at("s297")
        pc = T("≈ 0.45%  — not even half a percent", 32, WARN, weight=BOLD).move_to(DOWN * 1.75)
        self.play(FadeOut(VGroup(f1, f2, tm)), ReplacementTransform(res, pc), run_time=0.7)
        # s298 three words
        self.at("s298")
        self.clear()
        w = VGroup(*[pill(x, c, 48) for x, c in (("NOT", BLUE_), ("OR", AQUA), ("AND", ORANGE_))]).arrange(RIGHT, buff=0.8).move_to(UP * 0.3)
        self.play(LaggedStart(*[FadeIn(x, scale=0.7) for x in w], lag_ratio=0.2), run_time=0.9)
        ev = T("same tools, every game", 34, INK2).next_to(w, DOWN, buff=0.6)
        self.w("s298", "tools")
        self.play(FadeIn(ev), run_time=0.5)
        self.finish()

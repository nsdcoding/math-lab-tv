import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from pkit import *

RX = 3.7


class S20Given(PBase):
    CHAPTER = "Given That"

    def grid(self):
        g = DiceGrid(0.62, fs=26).move_to(LEFT * 3.0 + DOWN * 0.05)
        s = g.sums()
        return g, s

    def side(self, *ms, y0=1.6, buff=0.35):
        col = VGroup(*ms).arrange(DOWN, buff=buff)
        col.move_to([RX, y0 - col.height / 2, 0])
        for m in col:
            if m.width > 6.4: m.scale_to_fit_width(6.4)
            m.set_x(RX)
        return col

    def construct(self):
        self.at("s318")
        g, sums = self.grid()
        env = ic_card(WARN, 1.6, 1.1, "clue", WARN).move_to(RIGHT * RX + UP * 0.3)
        self.play(FadeIn(g), FadeIn(sums), run_time=0.6)
        self.w("s318", "clue")
        self.play(FadeIn(env, shift=LEFT * 0.4), run_time=0.6)
        # s319 definition
        self.at("s319")
        dc = def_card("CONDITIONAL PROBABILITY", "the chance of A, given B is true", VIOLET, 28)
        dc.scale_to_fit_width(min(dc.width, 12.6)).move_to(UP * 2.85)
        self.play(FadeIn(dc), run_time=0.7)
        # s320 clue shrinks the grid
        self.at("s320")
        big = pill("a clue shrinks the grid", WARN, 34).move_to(RIGHT * RX + DOWN * 1.2)
        self.w("s320", "clue")
        self.play(FadeIn(big), *g.tint(lambda a, b: a < 4, CELL_FILL, 0.25), run_time=0.8)
        self.play(*g.reset(), run_time=0.5)
        # s321 orange is 6
        self.at("s321")
        self.play(FadeOut(VGroup(env, big)), run_time=0.3)
        sb = boxed(T("“the orange die is a 6!”", 32, ORANGE_, weight=BOLD), ORANGE_, pad=0.28).move_to(RIGHT * RX + UP * 1.95)
        self.w("s321", "orange", nth=1)
        self.play(FadeIn(sb, shift=DOWN * 0.2), run_time=0.6)
        # s322 total 12?
        self.at("s322")
        q = T("total 12?", 38, INK, weight=BOLD).next_to(sb, DOWN, buff=0.3)
        self.play(FadeIn(q), run_time=0.4)
        # s323 cross out
        self.at("s323")
        was = T("before: 1/36", 30, MUTED).next_to(q, DOWN, buff=0.25)
        self.play(FadeIn(was), run_time=0.4)
        self.w("s323", "impossible")
        dim = VGroup(*[g.cells[k] for k in g.cells if k[0] != 6], *[t for t in sums if t.ob[0] != 6])
        self.play(dim.animate.set_opacity(0.12), run_time=0.9)
        self.qa_mute(dim)
        # s324 new world
        self.at("s324")
        col6 = g.where(lambda a, b: a == 6)
        self.play(col6.animate.set_fill(WARN, 0.45), run_time=0.5)
        nw = T("new world: 6 squares", 30, WARN, weight=BOLD).next_to(was, DOWN, buff=0.25)
        self.play(FadeIn(nw), run_time=0.4)
        # s325 1/6
        self.at("s325")
        self.w("s325", "twelve")
        self.play(g.c(6, 6).animate.set_fill(AQUA, 0.95), run_time=0.4)
        a = MathTex(r"{1 \over 6}", font_size=64, color=VIOLET).next_to(nw, DOWN, buff=0.25)
        self.w("s325", "sixth")
        self.play(Write(a), run_time=0.6)
        # s326 six times more likely
        self.at("s326")
        ba = T("1/36  →  1/6", 40, VIOLET, weight=BOLD).move_to(a)
        self.play(FadeOut(VGroup(was, nw)), ReplacementTransform(a, ba), run_time=0.6)
        # s327 notation
        self.at("s327")
        self.play(FadeOut(VGroup(dc, sb, q, ba)), run_time=0.4)
        nt = MathTex(r"P(", r"12", r"\mid", r"\text{orange } 6", r") = {1 \over 6}", font_size=64)
        nt[1].set_color(AQUA); nt[3].set_color(ORANGE_); nt[2].set_color(WARN)
        nt.move_to(RIGHT * RX + UP * 0.9)
        if nt.width > 6.6: nt.scale_to_fit_width(6.6)
        self.play(Write(nt), run_time=1.3)
        gv = T("“ | ” = given", 36, WARN, weight=BOLD).next_to(nt, DOWN, buff=0.5)
        self.w("s327", "given")
        self.play(FadeIn(gv), Indicate(nt[2], color=WARN, scale_factor=1.8), run_time=0.8)
        # s328 recipe
        self.at("s328")
        self.play(FadeOut(VGroup(nt, gv)), run_time=0.4)
        rc = MathTex(r"P(A \mid B)", "=", r"{\text{outcomes in A and B}", r"\over", r"\text{outcomes in B}}", font_size=46)
        rc[0].set_color(VIOLET); rc[2].set_color(AQUA); rc[4].set_color(WARN)
        rcb = boxed(rc, VIOLET, pad=0.3).move_to(RIGHT * RX + UP * 0.6)
        if rcb.width > 6.6: rcb.scale_to_fit_width(6.6)
        rcb.set_x(RX)
        self.play(FadeIn(rcb[0]), Write(rc), run_time=1.4)
        sw = T("count only inside the shrunken world", 28, WARN).next_to(rcb, DOWN, buff=0.35)
        if sw.width > 6.2: sw.scale_to_fit_width(6.2)
        self.w("s328", "shrunken")
        self.play(FadeIn(sw), run_time=0.5)
        # s329–s331 total 7
        self.at("s329")
        self.play(FadeOut(VGroup(rcb, sw)), g.c(6, 6).animate.set_fill(WARN, 0.45), run_time=0.4)
        q7 = T("orange is 6 → total 7?", 36, INK, weight=BOLD).move_to(RIGHT * RX + UP * 1.6)
        self.play(FadeIn(q7), run_time=0.5)
        self.at("s330")
        self.w("s330", "only")
        self.play(g.c(6, 1).animate.set_fill(AQUA, 0.95), run_time=0.4)
        a7 = MathTex(r"P(7 \mid \text{orange } 6) = {1 \over 6}", font_size=50, color=VIOLET).next_to(q7, DOWN, buff=0.4)
        self.w("s330", "one", nth=2)
        self.play(Write(a7), run_time=0.9)
        self.at("s331")
        b7 = MathTex(r"P(7) = {1 \over 6}", font_size=50, color=MUTED).next_to(a7, DOWN, buff=0.35)
        self.play(Write(b7), run_time=0.8)
        self.at("s332")
        same = pill("the clue changed nothing!", AQUA, 32).next_to(b7, DOWN, buff=0.35)
        self.play(FadeIn(same, scale=1.2), run_time=0.6)
        # s333 every column has one 7
        self.at("s333")
        self.play(FadeOut(VGroup(a7, b7, same, q7)), dim.animate.set_opacity(1), *g.reset(), run_time=0.6)
        self.qa_mute(dim, False)
        one = T("every column: exactly one 7", 32, AQUA, weight=BOLD).move_to(RIGHT * RX + UP * 0.6)
        self.play(FadeIn(one), run_time=0.4)
        for o in range(1, 7):
            self.play(g.where(lambda a, b, o=o: a == o).animate.set_fill(WARN, 0.3), g.c(o, 7 - o).animate.set_fill(AQUA, 0.95), run_time=0.3)
            self.play(g.where(lambda a, b, o=o: a == o and b != 7 - o).animate.set_fill(CELL_FILL, 1), run_time=0.15)
        # s334 independent
        self.at("s334")
        ind = def_card("INDEPENDENT", "the clue doesn't change the chance", WARN, 28)
        ind.scale_to_fit_width(min(ind.width, 6.6)).move_to(RIGHT * RX + DOWN * 0.6)
        self.play(FadeIn(ind), run_time=0.6)
        # s335–s340 at least 10, double?
        self.at("s335")
        self.play(FadeOut(VGroup(one, ind)), *g.reset(), run_time=0.4)
        sb = boxed(T("“the total is at least 10”", 32, ORANGE_, weight=BOLD), ORANGE_, pad=0.3).move_to(RIGHT * RX + UP * 1.6)
        self.play(FadeIn(sb), run_time=0.5)
        qd = T("a double?", 36, INK, weight=BOLD).next_to(sb, DOWN, buff=0.35)
        self.w("s335", "double")
        self.play(FadeIn(qd), run_time=0.4)
        self.at("s336")
        dim = VGroup(*[g.cells[k] for k in g.cells if sum(k) < 10], *[t for t in sums if sum(t.ob) < 10])
        self.w("s336", "shrink")
        self.play(dim.animate.set_opacity(0.12), run_time=0.8)
        self.qa_mute(dim)
        self.at("s337")
        order = [(4, 6), (5, 5), (6, 4), (5, 6), (6, 5), (6, 6)]
        ctr = TB("0", 48, WARN).next_to(qd, DOWN, buff=0.35)
        self.add(ctr)
        wds = [("four", 0), ("five", 0), ("six", 1), ("five", 2), ("six", 4), ("six", 6)]
        for k, (o, b) in enumerate(order):
            self.w("s337", wds[k][0], nth=wds[k][1])
            self.play(g.c(o, b).animate.set_fill(WARN, 0.5), Transform(ctr, TB(str(k + 1), 48, WARN).move_to(ctr)), run_time=0.3)
        self.at("s338")
        self.w("s338", "five")
        self.play(g.c(5, 5).animate.set_fill(AQUA, 0.95), run_time=0.35)
        self.w("s338", "six")
        self.play(g.c(6, 6).animate.set_fill(AQUA, 0.95), run_time=0.35)
        self.at("s339")
        ad = MathTex(r"{2 \over 6} = {1 \over 3}", font_size=60, color=VIOLET).next_to(qd, DOWN, buff=0.4)
        self.play(ReplacementTransform(ctr, ad), run_time=0.6)
        self.at("s340")
        bf = T("no clue: 1/6   →   with clue: 1/3", 30, WARN, weight=BOLD).next_to(ad, DOWN, buff=0.35)
        if bf.width > 6.4: bf.scale_to_fit_width(6.4)
        bf.set_x(RX)
        self.play(FadeIn(bf), run_time=0.6)
        # s341–s344 order matters
        self.at("s341")
        self.clear()
        hd = header("the order of a “given” matters", RED_, 32)
        self.play(FadeIn(hd), run_time=0.5)
        self.at("s342")
        g1 = DiceGrid(0.42, fs=18, titles=False).move_to(LEFT * 3.6 + UP * 0.6)
        for k, s in g1.cells.items():
            if k[0] != 6: s.set_fill(CELL_FILL, 0.2)
            else: s.set_fill(WARN, 0.45)
        g1.c(6, 6).set_fill(AQUA, 0.95)
        f1 = MathTex(r"P(12 \mid \text{orange } 6) = {1 \over 6}", font_size=46, color=VIOLET).next_to(g1, DOWN, buff=0.35)
        self.play(FadeIn(g1), Write(f1), run_time=1.0)
        self.at("s343")
        g2 = DiceGrid(0.42, fs=18, titles=False).move_to(RIGHT * 3.6 + UP * 0.6)
        for k, s in g2.cells.items():
            s.set_fill(CELL_FILL, 0.2)
        g2.c(6, 6).set_fill(AQUA, 0.95)
        f2 = MathTex(r"P(\text{orange } 6 \mid 12) = 1", font_size=46, color=VIOLET).next_to(g2, DOWN, buff=0.35)
        self.w("s343", "one")
        self.play(FadeIn(g2), Write(f2), run_time=1.0)
        cert = T("certain!", 32, AQUA, weight=BOLD).next_to(f2, DOWN, buff=0.2)
        self.w("s343", "certain")
        self.play(FadeIn(cert), run_time=0.4)
        self.at("s344")
        ne = TB("≠", 90, RED_).move_to(UP * 0.4)
        self.play(FadeIn(ne, scale=0.5), run_time=0.5)
        # s345 basketball
        self.at("s345")
        self.clear()
        c1 = boxed(VGroup(ic_ball(ORANGE_, 1.2), T("pro player → tall?", 30, INK, weight=BOLD), T("very likely", 30, AQUA, weight=BOLD)).arrange(DOWN, buff=0.3), ORANGE_, pad=0.4)
        c2 = boxed(VGroup(ic_person(INK2, 1.3), T("tall → pro player?", 30, INK, weight=BOLD), T("very unlikely", 30, RED_, weight=BOLD)).arrange(DOWN, buff=0.3), INK2, pad=0.4)
        VGroup(c1, c2).arrange(RIGHT, buff=1.6).move_to(UP * 0.2)
        ne = TB("≠", 80, RED_).move_to(UP * 0.2)
        self.play(FadeIn(c1, shift=UP * 0.2), run_time=0.6)
        self.w("s345", "most", nth=1)
        self.play(FadeIn(c2, shift=UP * 0.2), FadeIn(ne), run_time=0.6)
        # s346–s347 glasses
        self.at("s346")
        self.clear()
        hd = header("a class of 30 (illustration)", INK, 30)
        dots_ = VGroup()
        for k in range(30):
            d = Circle(0.26, stroke_color=INK2, stroke_width=3, fill_color=PANEL, fill_opacity=1)
            d.move_to(LEFT * 5.0 + RIGHT * (k % 10) * 0.72 + UP * (0.9 - (k // 10) * 0.72))
            dots_.add(d)
        gl = list(range(4, 10)) + list(range(14, 20))      # 12 glasses
        girls = gl[:8]
        self.play(FadeIn(hd), FadeIn(dots_, lag_ratio=0.02), run_time=0.8)
        self.w("s346", "twelve")
        self.play(*[dots_[k].animate.set_stroke(WARN, 5) for k in gl], run_time=0.5)
        self.w("s346", "eight")
        self.play(*[dots_[k].animate.set_fill(VIOLET, 0.85) for k in girls], run_time=0.5)
        lg = VGroup(T("glasses: 12 (yellow ring)", 26, WARN), T("girls with glasses: 8", 26, VIOLET)).arrange(DOWN, buff=0.2, aligned_edge=LEFT)
        lg.move_to(RIGHT * 4.3 + UP * 0.6)
        self.play(FadeIn(lg), run_time=0.4)
        self.at("s347")
        self.w("s347", "world")
        self.play(*[dots_[k].animate.set_opacity(0.15) for k in range(30) if k not in gl], run_time=0.7)
        a = MathTex(r"P(\text{girl} \mid \text{glasses}) = {8 \over 12} = {2 \over 3}", font_size=50, color=VIOLET).move_to(DOWN * 1.7)
        self.w("s347", "eight")
        self.play(Write(a), run_time=1.2)
        # s333a picture cards
        self.at("s333a")
        self.clear()
        dg = deck_grid().move_to(UP * 0.5)
        self.play(FadeIn(dg), run_time=0.6)
        self.w("s333a", "picture")
        dim = VGroup(*[s for k, s in dg.cells.items() if k[0] < 10])
        self.play(dim.animate.set_opacity(0.12), run_time=0.7)
        self.qa_mute(dim)
        self.w("s333a", "twelve")
        self.play(dg.where(lambda r, s: r >= 10).animate.set_fill(WARN, 0.45), run_time=0.5)
        self.w("s333a", "four", nth=0)
        self.play(dg.where(lambda r, s: r == 12).animate.set_fill(AQUA, 0.9), run_time=0.5)
        a = MathTex(r"P(K \mid \text{picture card}) = {4 \over 12} = {1 \over 3}", font_size=50, color=VIOLET).move_to(DOWN * 1.75)
        self.w("s333a", "third")
        self.play(Write(a), run_time=1.0)
        # s348
        self.at("s348")
        self.clear()
        fb = MathTex(r"{\text{what you want, inside the clue's world}", r"\over", r"\text{the world the clue puts you in}}", font_size=52)
        fb[0].set_color(AQUA); fb[2].set_color(WARN)
        fbb = boxed(fb, WARN, pad=0.4).move_to(UP * 0.3)
        self.play(FadeIn(fbb[0]), Write(fb), run_time=1.2)
        self.play(Indicate(fb[2], color=WARN), run_time=0.8)
        self.finish()

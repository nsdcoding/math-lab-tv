def stall():
    roof = Polygon(LEFT * 2.0 + UP * 1.0, RIGHT * 2.0 + UP * 1.0, RIGHT * 1.6 + UP * 1.6, LEFT * 1.6 + UP * 1.6).set_stroke(ORANGE_, 4)
    stripes = VGroup(*[Line(LEFT * 2.0 + RIGHT * k * 0.5 + UP * 1.0, LEFT * 1.6 + RIGHT * k * 0.4 + UP * 1.6, color=ORANGE_, stroke_width=2) for k in range(1, 9)])
    p1 = Line(LEFT * 1.9 + UP * 1.0, LEFT * 1.9 + DOWN * 1.2, color=INK2, stroke_width=4)
    p2 = Line(RIGHT * 1.9 + UP * 1.0, RIGHT * 1.9 + DOWN * 1.2, color=INK2, stroke_width=4)
    counter = Rectangle(width=4.2, height=0.7, stroke_color=INK2, stroke_width=4).move_to(DOWN * 0.9)
    dd = VGroup(die(3, ORANGE_, 0.5), die(4, BLUE_, 0.5)).arrange(RIGHT, buff=0.2).move_to(UP * 0.1)
    return VGroup(roof, stripes, p1, p2, counter, dd)


def token(s=0.3):
    c = Circle(s, stroke_color=WARN, stroke_width=3, fill_color=WARN, fill_opacity=0.25)
    return VGroup(c, Circle(s * 0.6, stroke_color=WARN, stroke_width=2))



import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from pkit import *


def trap_tag(n, text):
    return pill(f"TRAP {n}: {text}", RED_, 32).move_to(UP * 2.85)


class S25Mistakes(PBase):
    CHAPTER = "Common Mistakes"

    def construct(self):
        self.at("s404")
        hd = header("the traps", RED_, 36)
        cards = VGroup(*[card(2.6, 2.4, RED_) for _ in range(4)]).arrange(RIGHT, buff=0.35).move_to(DOWN * 0.1)
        nums = VGroup(*[TB(str(k + 1), 64, RED_).move_to(c) for k, c in enumerate(cards)])
        self.play(FadeIn(hd), LaggedStart(*[FadeIn(c, shift=UP * 0.3) for c in cards], lag_ratio=0.15), FadeIn(nums, lag_ratio=0.15), run_time=1.0)

        # trap 1: due for a win
        self.at("s405")
        self.clear()
        hd = trap_tag(1, "“I'm due!”")
        self.play(FadeIn(hd), run_time=0.5)
        self.at("s406")
        row = VGroup(*[coin("H", WARN, 0.45) for _ in range(5)], coin("?", MUTED, 0.45)).arrange(RIGHT, buff=0.25).move_to(UP * 1.0)
        self.play(LaggedStart(*[FadeIn(c, shift=DOWN * 0.3) for c in row[:5]], lag_ratio=0.15), run_time=1.0)
        self.w("s406", "tails")
        self.play(FadeIn(row[5]), run_time=0.4)
        self.play(Rotate(row[5], PI), run_time=0.5)
        self.at("s407")
        bar2 = VGroup(Rectangle(width=2.4, height=0.6, stroke_width=0, fill_color=WARN, fill_opacity=0.8),
                      Rectangle(width=2.4, height=0.6, stroke_width=0, fill_color=BLUE_, fill_opacity=0.8)).arrange(RIGHT, buff=0.05).move_to(DOWN * 0.6)
        for b in bar2: b.qa_container = True
        bl = VGroup(T("H  1/2", 28, BG, weight=BOLD).move_to(bar2[0]), T("T  1/2", 28, BG, weight=BOLD).move_to(bar2[1]))
        nm = T("the coin has no memory", 34, INK, weight=BOLD).move_to(DOWN * 1.75)
        self.play(FadeIn(nm), run_time=0.5)
        self.w("s407", "half")
        self.play(FadeIn(bar2), FadeIn(bl), run_time=0.6)
        self.at("s408")
        ind = pill("each flip is independent", AQUA, 30).move_to(DOWN * 1.75)
        self.play(ReplacementTransform(nm, ind), run_time=0.6)
        # diluted
        self.at("s409")
        self.play(FadeOut(VGroup(row, bar2, bl, ind)), run_time=0.4)
        ax = Axes(x_range=[0, 4, 1], y_range=[0.3, 1, 0.1], x_length=9.5, y_length=3.4,
                  axis_config=dict(color=INK2, stroke_width=3, include_tip=False, include_ticks=False)).move_to(DOWN * 0.15)
        xl = VGroup(*[T(s, 22, INK2).next_to(ax.c2p(v, 0.3), DOWN, buff=0.12) for v, s in zip(range(5), ("1", "10", "100", "1,000", "10,000"))])
        xt = T("number of flips (starting with 5 heads)", 22, MUTED).next_to(xl, DOWN, buff=0.1)
        yl = VGroup(*[T(f"{int(v * 100)}%", 22, INK2).next_to(ax.c2p(0, v), LEFT, buff=0.12) for v in (0.5, 1.0)])
        half = DashedLine(ax.c2p(0, 0.5), ax.c2p(4, 0.5), color=INK2, dash_length=0.12)
        xs = np.linspace(np.log10(5), 4, 80)
        cur = VMobject(stroke_color=WARN, stroke_width=5).set_points_smoothly([ax.c2p(x, 0.5 + 2.5 / (10 ** x)) for x in xs])
        cur.qa_ignore = True
        self.play(FadeIn(VGroup(ax, xl, xt, yl)), Create(half), run_time=0.6)
        self.w("s409", "correcting")
        self.play(Create(cur), run_time=2.0)
        dl = pill("diluted, not corrected", AQUA, 30).move_to(ax.c2p(2.8, 0.85))
        self.w("s409", "diluted")
        self.play(FadeIn(dl), run_time=0.5)
        # s410 sequences
        self.at("s410")
        self.play(FadeOut(VGroup(ax, xl, xt, yl, half, cur, dl)), run_time=0.4)
        def strip(s):
            return VGroup(*[coin(f, WARN if f == "H" else BLUE_, 0.36) for f in s]).arrange(RIGHT, buff=0.15)
        s1, s2 = strip("HHHHHT"), strip("HHHHHH")
        VGroup(s1, s2).arrange(DOWN, buff=0.6).move_to(LEFT * 1.2 + UP * 0.2)
        t1 = T("1/64", 40, VIOLET, weight=BOLD).next_to(s1, RIGHT, buff=0.7)
        t2 = T("1/64", 40, VIOLET, weight=BOLD).next_to(s2, RIGHT, buff=0.7)
        self.play(FadeIn(s1), run_time=0.6)
        self.w("s410", "six")
        self.play(FadeIn(s2), run_time=0.6)
        self.w("s410", "one")
        self.play(FadeIn(t1), FadeIn(t2), run_time=0.5)
        self.at("s411")
        nm = big_word("the gambler's fallacy", RED_, 52).move_to(DOWN * 1.8)
        self.play(FadeIn(nm, scale=0.9), run_time=0.6)
        # s412–s413 small samples
        self.at("s412")
        self.play(FadeOut(VGroup(s1, s2, t1, t2, nm)), run_time=0.4)
        shots = VGroup(*[VGroup(ic_ball(ORANGE_, 0.8), check(AQUA, 0.3)).arrange(DOWN, buff=0.15) for _ in range(3)]).arrange(RIGHT, buff=0.6).move_to(LEFT * 3.0 + UP * 0.3)
        sb = boxed(T("“never misses!”", 34, INK, weight=BOLD), INK2, pad=0.3).move_to(RIGHT * 3.2 + UP * 0.6)
        self.w("s412", "three")
        self.play(LaggedStart(*[FadeIn(s, shift=UP * 0.2) for s in shots], lag_ratio=0.25), run_time=1.0)
        self.w("s412", "never")
        self.play(FadeIn(sb), run_time=0.5)
        self.at("s413")
        sw = pill("small samples wobble", WARN, 32).move_to(DOWN * 1.6)
        ex = T("remember: 7 heads in 10 flips", 28, INK2).next_to(sb, DOWN, buff=0.4)
        self.w("s413", "remember")
        self.play(FadeIn(ex), run_time=0.5)
        self.w("s413", "small")
        self.play(FadeIn(sw), run_time=0.5)

        # trap 2: two outcomes -> 50/50
        self.at("s414")
        self.clear()
        hd = trap_tag(2, "two outcomes → 50/50?")
        self.play(FadeIn(hd), run_time=0.5)
        self.at("s415")
        tk = ic_ticket(WARN, 1.6).move_to(LEFT * 3.4 + UP * 0.2)
        wl = VGroup(pill("win", AQUA, 32), pill("lose", MUTED, 32)).arrange(RIGHT, buff=0.4).next_to(tk, DOWN, buff=0.5)
        g = MathTex(r"{1 \over 2}\,?", font_size=72, color=MUTED).move_to(RIGHT * 2.0 + UP * 0.2)
        self.play(FadeIn(tk), FadeIn(wl), run_time=0.6)
        self.w("s415", "fifty")
        self.play(Write(g), run_time=0.5)
        self.at("s416")
        xx = cross(RED_, 0.5).move_to(g); [setattr(m, "qa_ignore", True) for m in xx]
        sp = spinner([(0.75, RED_), (0.25, BLUE_)], r=1.1).move_to(RIGHT * 4.6 + UP * 0.2)
        self.play(Create(xx), run_time=0.4)
        self.w("s416", "spinner")
        self.play(FadeIn(sp), run_time=0.5)
        self.at("s417")
        rl = pill("only if the outcomes are equally likely", WARN, 32).move_to(DOWN * 1.9)
        self.play(FadeIn(rl), run_time=0.5)

        # trap 3: adding blindly
        self.at("s418")
        self.clear()
        hd = trap_tag(3, "adding when you shouldn't")
        self.play(FadeIn(hd), run_time=0.5)
        self.at("s419")
        w = T("4 rolls: 4/6 ≈ 67%", 40, RED_, weight=BOLD).move_to(LEFT * 3.2 + UP * 0.6)
        xx = cross(RED_, 0.5).move_to(w); [setattr(m, "qa_ignore", True) for m in xx]
        r = T("1 − (5/6)⁴ ≈ 52%", 40, VIOLET, weight=BOLD).move_to(RIGHT * 3.2 + UP * 0.6)
        self.play(FadeIn(w), run_time=0.5)
        self.w("s419", "not")
        self.play(Create(xx), FadeIn(r), run_time=0.6)
        ov = T("events that overlap: adding counts too much", 30, INK2).move_to(DOWN * 0.7)
        self.w("s419", "overlap")
        self.play(FadeIn(ov), run_time=0.5)
        self.at("s420")
        self.play(FadeOut(VGroup(w, xx, r, ov)), run_time=0.4)
        gg = gauge(100, AQUA, "never above 1 (100%)", r=1.5)
        gg.move_to(UP * 0.1)
        self.play(FadeIn(gg), run_time=0.7)
        bad = T("answer > 1 → something went wrong", 32, RED_, weight=BOLD).move_to(DOWN * 1.95)
        self.w("s420", "more")
        self.play(FadeIn(bad), run_time=0.5)

        # trap 4: flipping the given
        self.at("s421")
        self.clear()
        hd = trap_tag(4, "flipping the given")
        self.play(FadeIn(hd), run_time=0.5)
        self.at("s422")
        f = MathTex(r"P(A \mid B)", r"\neq", r"P(B \mid A)", font_size=84)
        f[0].set_color(VIOLET); f[1].set_color(RED_); f[2].set_color(AQUA)
        f.move_to(UP * 0.9)
        self.play(Write(f), run_time=1.0)
        ex = VGroup(T("tall, given basketball player: very likely", 28, VIOLET), T("basketball player, given tall: very unlikely", 28, AQUA)).arrange(DOWN, buff=0.25).move_to(DOWN * 0.9)
        self.w("s422", "tall")
        self.play(FadeIn(ex, lag_ratio=0.4), run_time=1.0)
        self.at("s423")
        wg = pill("which group am I really looking at?", WARN, 34).move_to(DOWN * 2.05)
        self.play(FadeIn(wg), run_time=0.5)

        # bonus
        self.at("s424")
        self.clear()
        hd = pill("BONUS TRAP: unlikely = impossible?", RED_, 32).move_to(UP * 2.85)
        self.play(FadeIn(hd), run_time=0.5)
        self.at("s425")
        rng = np.random.default_rng(12)
        pts = [(x, y) for x, y in zip(rng.uniform(-6, 6, 900), rng.uniform(-2.0, 1.8, 900)) if not (abs(y + 0.1) < 0.55 and abs(x) < 4.4)]
        dots_ = VGroup(*[Dot([x, y, 0], radius=0.035, color=GRID) for x, y in pts])
        self.play(FadeIn(dots_, lag_ratio=0.001), run_time=1.0)
        hit = VGroup(*[Dot(d.get_center(), radius=0.09, color=WARN) for d in dots_[::30]])
        il = T("illustration", 22, MUTED).move_to(RIGHT * 5.8 + DOWN * 2.2)
        self.w("s425", "country")
        self.play(FadeIn(hit, lag_ratio=0.05), FadeIn(il), run_time=1.2)
        rr = pill("rare for one, expected for many", WARN, 32).move_to(DOWN * 0.1)
        self.w("s425", "dozens")
        self.play(FadeIn(rr), run_time=0.5)
        self.at("s426")
        rr2 = pill("enough chances → surprises are normal", AQUA, 32).move_to(DOWN * 0.1)
        self.play(ReplacementTransform(rr, rr2), run_time=0.6)
        self.finish()
